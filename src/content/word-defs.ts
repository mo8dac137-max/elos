/**
 * The raw word data behind the vocabulary packs (Milestone K1 split):
 * word-pack.ts holds only the deterministic builders, this file holds the
 * 72 WordDef entries. One word = one curriculum unit with the dominant
 * beginner sense, flowing through the same kernel, planner, review schedule
 * and session UI as grammar units.
 *
 * Batch selection method (researched 2026-11-05):
 * - Frequency first (Zipf's law): words come from the A1 band of the Oxford
 *   3000 and the head of the New General Service List, whose first 1,000
 *   words already cover ~82% of everyday English.
 * - Batch 3 completes the A1 core-verb set (make, say, look, like take the
 *   gaps next to go/know/see/want/need) and the time cluster (hour, minute,
 *   month next to day/week/year/time), adds everyday objects (bed, door,
 *   room, bus, street) and the owner's service/health goals (customer,
 *   message, problem for the call-centre line; pain for the pharmacy line).
 * - Every `mistake` note targets a documented Arabic-speaker error
 *   (article omission, make/do, call me vs call to me, look at, wait for,
 *   say vs tell, people vs person, everything vs every things).
 *
 * Batches 1-2 (I1/I3) are unchanged and keep their order, so existing
 * learner progress and review states are preserved.
 *
 * Everything here is deterministic: no clock, no randomness, no I/O.
 */

export interface WordDef {
  /** The lemma itself, lowercase, used in ids, prompts and answers. */
  id: string;
  pos: 'noun' | 'verb';
  /** The primary A1 Arabic gloss. */
  gloss: string;
  /** A short English gloss used as the note_en of generated items. */
  en: string;
  /** The Arabic teaching line shown on the intro card (summary_ar). */
  ar: string;
  /** One English sentence that contains the lemma exactly once, in the
   *  base form, lowercase, not at the start of the sentence. */
  example: string;
  /** A real, useful common-mistake note in Arabic (summary on the unit card). */
  mistake: string;
}

